/** Native identity for staged Windows/Linux workspaces, before release packaging. */
import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
import {constants} from 'node:fs';
import {digest, fileDigest} from './artifact-data.mjs';
import {runtimePackagePaths} from './runtime-package.mjs';
import {verifyElectronExecutable} from './targets.mjs';
import {packageRoot} from './package-resolution.mjs';

export const PORTABLE_IDENTITY = Object.freeze({name:'Blackcrab', company:'Jonathan Benn', launcher:'blackcrab', desktopId:'com.bonjenn.blackcrab'});
const assets = new URL('./assets/', import.meta.url);

export function portableVersion(version) {
  if (typeof version !== 'string' || !/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version)) throw Error('Portable metadata requires a release version');
  const parts = version.split('.').map(Number);
  if (parts.some(n=>n>65535)) throw Error('Portable version exceeds Windows version bounds');
  return [...parts,0];
}

export function linuxDesktopEntry(version) {
  portableVersion(version);
  // This is a template for the OUTER launcher package. The managed workspace
  // needs its owner's authenticated channels and must not be launched directly.
  return `[Desktop Entry]\nType=Application\nVersion=1.0\nName=Blackcrab\nComment=A workspace for coding agents\nExec=blackcrab %U\nIcon=${PORTABLE_IDENTITY.desktopId}\nTerminal=false\nCategories=Development;IDE;\nStartupWMClass=Blackcrab\nMimeType=x-scheme-handler/blackcrab;\nX-Blackcrab-Version=${version}\n`;
}

export async function loadWindowsResourceEditor(source) {
  if (typeof source !== 'string' || !path.isAbsolute(source)) throw Error('Absolute frozen dependency source required');
  const builder=await packageRoot('electron-builder',path.join(source,'apps/desktop'));
  const library=await packageRoot('app-builder-lib',builder.root);
  const editor=await packageRoot('resedit',library.root);
  if (editor.value.version !== '1.7.2') throw Error('Windows resource editor differs from frozen dependency graph');
  return createRequire(path.join(editor.root,'package.json'))(editor.root);
}

function windowsStrings(version) {
  const fileVersion=portableVersion(version).join('.');
  return {CompanyName:PORTABLE_IDENTITY.company,FileDescription:PORTABLE_IDENTITY.name,ProductName:PORTABLE_IDENTITY.name,InternalName:PORTABLE_IDENTITY.name,OriginalFilename:'Blackcrab.exe',FileVersion:fileVersion,ProductVersion:version};
}
function iconDigest(icon) { return digest(Buffer.from(icon.isRaw()?icon.bin:icon.generate())); }
function nonResourceSections(exe) {
  const resource=exe.getSectionByEntry(2),relocations=exe.getSectionByEntry(5);
  // A larger .rsrc can move the following relocation table. Its bytes and
  // relative directory offset must stay intact; code/data addresses cannot move.
  return exe.getAllSections().filter(s=>s!==resource).map(s=>({name:s.info.name,virtualAddress:s===relocations&&!(s.info.characteristics&0x20000000)?'relocation-table':s.info.virtualAddress,virtualSize:s.info.virtualSize,characteristics:s.info.characteristics,sha256:s.data?digest(Buffer.from(s.data)):null}));
}
function loaderDirectories(exe) {
  const directories=exe.newHeader.optionalHeaderDataDirectory;
  return Array.from({length:16},(_,i)=>i).filter(i=>i!==2&&i!==4).map(i=>{
    const d=directories.get(i),section=i===5?exe.getSectionByEntry(5):null;
    return {id:i,address:section?d.virtualAddress-section.info.virtualAddress:d.virtualAddress,size:d.size};
  });
}
function unchangedResources(entries) {
  return entries.filter(e=>![3,14,16].includes(e.type)).map(e=>({type:e.type,id:e.id,lang:e.lang,codepage:e.codepage,sha256:digest(Buffer.from(e.bin))})).sort((a,b)=>JSON.stringify(a).localeCompare(JSON.stringify(b)));
}

/** Reparse generated bytes; do not trust an in-memory edit or a renamed .exe. */
export function verifyWindowsMetadata(binary,iconBytes,version,editor) {
  const parts=portableVersion(version),expected=windowsStrings(version);
  const exe=editor.NtExecutable.from(binary,{ignoreCert:true});
  if(exe.is32bit()||exe.newHeader.fileHeader.machine!==0x8664) throw Error('Windows metadata requires x64 PE');
  const resources=editor.NtExecutableResource.from(exe);
  const versions=editor.Resource.VersionInfo.fromEntries(resources.entries);
  if (!versions.length) throw Error('Windows version resource missing');
  let tables=0;
  for(const info of versions) {
    const languages=info.getAllLanguagesForStringValues();
    if(!languages.length) throw Error('Windows version translations missing');
    for(const lang of languages) {
      const strings=info.getStringValues(lang);
      for(const [key,value] of Object.entries(expected)) if(strings[key]!==value) throw Error('Windows identity/version resource mismatch: '+key);
      tables++;
    }
    const ms=(parts[0]*65536+parts[1])>>>0,ls=(parts[2]*65536)>>>0;
    if(info.fixedInfo.fileVersionMS!==ms||info.fixedInfo.productVersionMS!==ms||info.fixedInfo.fileVersionLS!==ls||info.fixedInfo.productVersionLS!==ls) throw Error('Windows fixed version mismatch');
  }
  const icons=editor.Data.IconFile.from(iconBytes).icons.map(i=>iconDigest(i.data));
  const groups=editor.Resource.IconGroupEntry.fromEntries(resources.entries);
  if(!icons.length||!groups.length) throw Error('Windows application icon missing');
  for(const group of groups) if(JSON.stringify(group.getIconItemsFromEntries(resources.entries).map(iconDigest))!==JSON.stringify(icons)) throw Error('Windows application icon mismatch');
  return {version,versionTables:tables,iconGroups:groups.length,iconSha256:digest(iconBytes)};
}

export function rewriteWindowsMetadata(binary,iconBytes,version,editor) {
  const parts=portableVersion(version),strings=windowsStrings(version);
  // Authenticode is invalidated by changing resources. The resulting staged
  // executable is explicitly unsigned; release packaging owns any later signing.
  const exe=editor.NtExecutable.from(binary,{ignoreCert:true});
  if(exe.is32bit()||exe.newHeader.fileHeader.machine!==0x8664) throw Error('Windows metadata requires x64 PE');
  const resources=editor.NtExecutableResource.from(exe);
  const sections=nonResourceSections(exe),directories=loaderDirectories(exe),otherResources=unchangedResources(resources.entries);
  const versions=editor.Resource.VersionInfo.fromEntries(resources.entries);
  if(!versions.length) throw Error('Windows version resource missing');
  for(const info of versions) {
    info.setFileVersion(...parts,1033);info.setProductVersion(...parts,1033);
    for(const language of info.getAllLanguagesForStringValues()) info.setStringValues(language,strings);
    info.outputToResourceEntries(resources.entries);
  }
  const icons=editor.Data.IconFile.from(iconBytes).icons.map(i=>i.data);
  if(!icons.length) throw Error('Blackcrab icon is empty');
  const groups=editor.Resource.IconGroupEntry.fromEntries(resources.entries);
  if(!groups.length) throw Error('Windows application icon resource missing');
  for(const group of groups) editor.Resource.IconGroupEntry.replaceIconsForResource(resources.entries,group.id,group.lang,icons);
  resources.outputResource(exe);
  const output=Buffer.from(exe.generate());
  const reparsed=editor.NtExecutable.from(output);
  if(JSON.stringify(nonResourceSections(reparsed))!==JSON.stringify(sections)||JSON.stringify(loaderDirectories(reparsed))!==JSON.stringify(directories)) throw Error('Windows resource rewrite changed executable code or loader directories');
  if(JSON.stringify(unchangedResources(editor.NtExecutableResource.from(reparsed).entries))!==JSON.stringify(otherResources)) throw Error('Windows resource rewrite changed unrelated resources');
  verifyWindowsMetadata(output,iconBytes,version,editor);
  return output;
}

async function regular(file) { const s=await fs.lstat(file);if(!s.isFile()||s.isSymbolicLink()||s.nlink!==1)throw Error('Metadata output must be a regular unlinked file');return s; }
async function absent(file) { try { await fs.lstat(file); } catch(e) { if(e.code==='ENOENT')return;throw e; } throw Error('Metadata output already exists'); }
async function checkedLayout(root,targetId) {
  const layout=runtimePackagePaths(root,targetId);
  if(!['win32-x64','linux-x64'].includes(targetId))throw Error('Portable metadata requires Windows or Linux');
  for(const dir of [root,layout.resources]) { const s=await fs.lstat(dir);if(!s.isDirectory()||s.isSymbolicLink())throw Error('Metadata requires a real staging directory'); }
  await regular(layout.executable);await verifyElectronExecutable(layout.executable,targetId);
  return layout;
}

export async function stagePortableMetadata({root,targetId,version,source}) {
  portableVersion(version);
  const layout=await checkedLayout(root,targetId);
  const iconName=targetId==='win32-x64'?'icon.ico':'icon.png';
  const iconFile=path.join(layout.resources,iconName),recordFile=path.join(layout.resources,'blackcrab-native-identity.json');
  const desktopFile=path.join(layout.resources,PORTABLE_IDENTITY.desktopId+'.desktop');
  for(const file of [iconFile,recordFile,...(targetId==='linux-x64'?[desktopFile]:[])])await absent(file);
  const icon=await fs.readFile(new URL(iconName,assets));
  let windows;
  if(targetId==='win32-x64') {
    const editor=await loadWindowsResourceEditor(source),before=await fs.readFile(layout.executable);
    const output=rewriteWindowsMetadata(before,icon,version,editor);
    // Only mutate the freshly staged executable after the complete rewrite has
    // passed verification; a failed producer never publishes its staging tree.
    await fs.writeFile(layout.executable,output);
    windows=verifyWindowsMetadata(await fs.readFile(layout.executable),icon,version,editor);
  }
  await fs.copyFile(new URL(iconName,assets),iconFile,constants.COPYFILE_EXCL);
  if(targetId==='linux-x64')await fs.writeFile(desktopFile,linuxDesktopEntry(version),{flag:'wx',mode:0o644});
  const record={target:targetId,...PORTABLE_IDENTITY,version,icon:iconName,iconSha256:digest(icon),...(windows?{windows,signing:'unsigned-after-resource-edit'}:{desktopEntry:path.basename(desktopFile),desktopEntryRole:'outer-launcher-template'})};
  await fs.writeFile(recordFile,JSON.stringify(record,null,2)+'\n',{flag:'wx',mode:0o644});
  return record;
}

export async function verifyPortableMetadata({root,targetId,version,source}) {
  portableVersion(version);
  const layout=await checkedLayout(root,targetId),iconName=targetId==='win32-x64'?'icon.ico':'icon.png';
  const icon=await fs.readFile(new URL(iconName,assets));
  const recordFile=path.join(layout.resources,'blackcrab-native-identity.json'),iconFile=path.join(layout.resources,iconName);
  await regular(recordFile);await regular(iconFile);
  const record=JSON.parse(await fs.readFile(recordFile,'utf8'));
  if(record.target!==targetId||record.version!==version||record.icon!==iconName||record.iconSha256!==digest(icon)||await fileDigest(iconFile)!==digest(icon)||Object.entries(PORTABLE_IDENTITY).some(([k,v])=>record[k]!==v))throw Error('Portable application identity mismatch');
  if(targetId==='win32-x64') {
    const editor=await loadWindowsResourceEditor(source);
    verifyWindowsMetadata(await fs.readFile(layout.executable),icon,version,editor);
  } else {
    const file=path.join(layout.resources,PORTABLE_IDENTITY.desktopId+'.desktop');await regular(file);
    if(await fs.readFile(file,'utf8')!==linuxDesktopEntry(version))throw Error('Linux launcher template mismatch');
  }
  return record;
}
