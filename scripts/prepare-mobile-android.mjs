#!/usr/bin/env node
/**
 * Isolated, reproducible Expo SDK 58 Android preparation and APK build.
 * Mirrors prepare-mobile-ios.mjs: physical whitespace-free staging, isolated HOME/npm,
 * no edits to shared dependencies, JSON report with artifact hashes.
 *
 * The product is a Release APK signed with the generated Expo debug keystore. That is
 * installable on a device or emulator (sideload/internal testing) but is NOT a Play Store
 * artifact: an upload-key-signed AAB and Play Console setup are separate gates.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { execFile } from 'node:child_process';
import { promisify, parseArgs } from 'node:util';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  createSourceSnapshot, runLogged, verifyNativeInstallInputs, verifyNativeDependencyRoots,
  isolatedBuildEnvironment, resolveNativeEntry, resolveNpmCache,
} from './prepare-mobile-ios.mjs';

const execute = promisify(execFile);
const defaultRepo = fileURLToPath(new URL('../', import.meta.url));
const hash = data => createHash('sha256').update(data).digest('hex');
const inside = (root, target) => target === root || target.startsWith(root + path.sep);
const EXPECTED_PACKAGE = 'dev.blackcrab.remote';

/** Resolve and validate the Android toolchain; paths must be physical and whitespace-free. */
export async function resolveAndroidToolchain({ javaHome = process.env.JAVA_HOME, androidHome = process.env.ANDROID_HOME } = {}) {
  if (!javaHome || !androidHome) throw new Error('Set JAVA_HOME (JDK 17) and ANDROID_HOME, or pass --java-home/--android-home.');
  const java = await fs.realpath(javaHome), sdk = await fs.realpath(androidHome);
  for (const dir of [java, sdk]) if (/\s/.test(dir)) throw new Error(`Android tooling breaks on whitespace paths: ${dir}`);
  await fs.access(path.join(java, 'bin/java'));
  await fs.access(path.join(sdk, 'platforms'));
  return { javaHome: java, androidHome: sdk };
}

/** Only these public values may reach the build; account tokens and credentials are never forwarded. */
export function publicBuildConfiguration({ easProjectId, updateChannel, updatesEnabled } = {}) {
  const config = {};
  if (easProjectId !== undefined) config.BLACKCRAB_EAS_PROJECT_ID = String(easProjectId);
  if (updateChannel !== undefined) config.BLACKCRAB_UPDATE_CHANNEL = String(updateChannel);
  if (updatesEnabled !== undefined) config.BLACKCRAB_MOBILE_UPDATES_ENABLED = String(updatesEnabled);
  for (const [name, value] of Object.entries(config)) if (!/^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$/.test(value)) throw new Error(`Unsupported value for ${name}.`);
  return config;
}

export function androidBuildEnvironment(root, toolchain, { gradleUserHome, original = process.env, publicConfig = {} } = {}) {
  const env = { ...isolatedBuildEnvironment(root, original), ...publicConfig };
  env.JAVA_HOME = toolchain.javaHome;
  env.ANDROID_HOME = toolchain.androidHome;
  env.ANDROID_SDK_ROOT = toolchain.androidHome;
  env.GRADLE_USER_HOME = gradleUserHome ?? path.join(root, 'gradle-home');
  env.GRADLE_OPTS = '-Dorg.gradle.daemon=false -Dfile.encoding=UTF-8';
  env.PATH = [path.join(toolchain.javaHome, 'bin'), path.join(toolchain.androidHome, 'platform-tools'), env.PATH].join(path.delimiter);
  return env;
}

/**
 * Gradle would otherwise write build/ and .cxx/ inside the vendored module directories, and the consumer
 * integrity check (mobile-experience/consumer.mjs) rejects any extra file under vendor/t3-mobile whenever the
 * Expo config is read. This init script relocates only those projects' outputs under the given directory, and
 * adds the externally staged libghostty-vt include directory to their CMake compiler flags (AGP ignores CXXFLAGS).
 */
export function vendorOutputRelocationInitScript(outputRoot, { includeDirectory, signingProperties } = {}) {
  for (const dir of [outputRoot, includeDirectory, signingProperties].filter(Boolean)) if (!path.isAbsolute(dir) || /[\s'"\\$]/.test(dir)) throw new Error('Gradle paths must be absolute without whitespace, quotes, backslashes or $.');
  return `// Generated by scripts/prepare-mobile-android.mjs; keeps vendored sources unmodified.
allprojects { p ->
  if (p.projectDir.toString().contains('/vendor/t3-mobile/')) {
    def out = new File('${outputRoot}', p.path.replace(':', '_'))
    p.layout.buildDirectory.set(new File(out, 'build'))
    // AGP hard-links imported prebuilt libraries (jniLibs) into its CMake output; the consumer check rejects a
    // link count above 1. Replace each such file with an identical single-link copy once CMake has finished.
    p.tasks.configureEach { t ->
      if (t.name.startsWith('buildCMake')) {
        t.doLast {
          def libs = new File(p.projectDir, 'src/main/jniLibs')
          if (libs.isDirectory()) {
            libs.eachFileRecurse { f ->
              if (f.isFile() && java.nio.file.Files.getAttribute(f.toPath(), 'unix:nlink') > 1) {
                def tmp = new File(f.parentFile, f.name + '.relink')
                java.nio.file.Files.copy(f.toPath(), tmp.toPath(), java.nio.file.StandardCopyOption.COPY_ATTRIBUTES)
                java.nio.file.Files.move(tmp.toPath(), f.toPath(), java.nio.file.StandardCopyOption.REPLACE_EXISTING)
              }
            }
          }
        }
      }
    }
    p.afterEvaluate {
      def android = p.extensions.findByName('android')
      if (android != null && android.hasProperty('externalNativeBuild') && android.externalNativeBuild.hasProperty('cmake')) {
        android.externalNativeBuild.cmake.buildStagingDirectory = new File(out, 'cxx')${includeDirectory ? `
        android.defaultConfig.externalNativeBuild.cmake.cppFlags('-I${includeDirectory}')` : ''}
      }
    }
  }
}${signingProperties ? `
// Upload-key signing for the app module. Secrets are read here, at build time, from a private properties file;
// they are never placed in arguments, the environment, logs or the build report.
allprojects { p ->
  if (p.path == ':app') {
    p.afterEvaluate {
      def props = new Properties()
      new File('${signingProperties}').withInputStream { props.load(it) }
      def android = p.extensions.getByName('android')
      def upload = android.signingConfigs.maybeCreate('blackcrabUpload')
      upload.storeFile = new File(props.getProperty('storeFile'))
      upload.storePassword = props.getProperty('storePassword')
      upload.keyAlias = props.getProperty('keyAlias')
      upload.keyPassword = props.getProperty('keyPassword')
      android.buildTypes.getByName('release').signingConfig = upload
    }
  }
}` : ''}
`;
}

/** Release APK for one ABI by default: bounds build time/size; use --abis for a universal APK. */
export function gradleReleaseArguments({ abis = 'arm64-v8a', workers = 2, initScript, task = 'assembleRelease' } = {}) {
  if (!/^[a-z0-9_,-]+$/.test(abis)) throw new Error('Unsupported ABI list.');
  if (!['assembleRelease', 'bundleRelease'].includes(task)) throw new Error('Unsupported Gradle task.');
  return [...(initScript ? ['--init-script', initScript] : []), task, '--no-daemon', '--stacktrace', `-PreactNativeArchitectures=${abis}`, `-Dorg.gradle.workers.max=${workers}`, '-Dorg.gradle.jvmargs=-Xmx4g -XX:MaxMetaspaceSize=1g'];
}

/**
 * The vendored mobile export keeps the prebuilt Android libghostty-vt shared libraries but not the C headers
 * their JNI bridge compiles against. Fetch them from the pinned reference commit into a directory OUTSIDE the
 * staged repository (the consumer integrity check rejects extra files under vendor/t3-mobile), verifying every
 * git blob SHA, and expose them to CMake through the Gradle init script. Tracked vendor source and inventories are unchanged.
 */
export const GHOSTTY_REFERENCE = Object.freeze({ repository: 'BonJenn/t3code', commit: '7f02de2eb8e253e0ec23f005b3cfff8e2c963be8', directory: 'native/libghostty-vt' });
const gitBlobSha = bytes => createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex');

export async function stageGhosttyHeaders(destination, { fetchJson, fetchRaw, reference = GHOSTTY_REFERENCE } = {}) {
  const ghJson = fetchJson ?? (async route => JSON.parse((await execute('gh', ['api', route], { maxBuffer: 64 * 1024 * 1024 })).stdout));
  const ghRaw = fetchRaw ?? (async route => (await execute('gh', ['api', '-H', 'Accept: application/vnd.github.raw', route], { encoding: 'buffer', maxBuffer: 64 * 1024 * 1024 })).stdout);
  const tree = await ghJson(`repos/${reference.repository}/git/trees/${reference.commit}?recursive=1`);
  if (tree.truncated) throw new Error('Reference tree listing was truncated.');
  const wanted = tree.tree.filter(entry => entry.type === 'blob' && (entry.path.startsWith(`${reference.directory}/include/`) || entry.path === `${reference.directory}/VERSION`));
  if (!wanted.some(entry => entry.path === `${reference.directory}/include/ghostty/vt.h`)) throw new Error('Reference commit has no libghostty-vt headers.');
  const root = path.resolve(destination), records = [];
  for (const entry of wanted) {
    const parts = entry.path.split('/');
    if (parts.some(part => !part || part === '.' || part === '..')) throw new Error('Unsafe reference path.');
    const bytes = Buffer.from(await ghRaw(`repos/${reference.repository}/contents/${entry.path}?ref=${reference.commit}`));
    if (gitBlobSha(bytes) !== entry.sha) throw new Error(`Reference file failed blob verification: ${entry.path}`);
    const target = path.join(root, entry.path.slice(reference.directory.length + 1));
    if (!inside(root, target)) throw new Error('Reference path escapes staging.');
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, bytes);
    records.push({ path: entry.path, blobSha: entry.sha, sha256: hash(bytes) });
  }
  const version = records.find(entry => entry.path === `${reference.directory}/VERSION`);
  return { ...reference, destination: root, includeDirectory: path.join(root, 'include'), files: records.length, versionFileSha256: version?.sha256, records };
}

/**
 * Upload-key properties file (created by scripts/create-android-upload-key.mjs): storeFile, storePassword,
 * keyAlias, keyPassword and certificateFile. It must be owner-only and live outside the repository and stage.
 * Returns only non-secret fields plus the validated path.
 */
export async function readUploadKeyProperties(file) {
  const resolved = await fs.realpath(path.resolve(file));
  if (/[\s'"\\$]/.test(resolved)) throw new Error('Upload key properties path must not contain whitespace, quotes, backslashes or $.');
  const stat = await fs.stat(resolved);
  if (!stat.isFile() || (stat.mode & 0o077) !== 0) throw new Error('Upload key properties must be a regular file readable only by its owner.');
  const props = Object.fromEntries((await fs.readFile(resolved, 'utf8')).split('\n').filter(line => line && !line.startsWith('#')).map(line => { const i = line.indexOf('='); return [line.slice(0, i), line.slice(i + 1)]; }));
  for (const key of ['storeFile', 'storePassword', 'keyAlias', 'keyPassword', 'certificateFile']) if (!props[key]) throw new Error(`Upload key properties are missing ${key}.`);
  for (const key of ['storeFile', 'certificateFile']) if (!path.isAbsolute(props[key])) throw new Error(`${key} must be an absolute path.`);
  await fs.access(props.storeFile); await fs.access(props.certificateFile);
  return { file: resolved, storeFile: props.storeFile, keyAlias: props.keyAlias, certificateFile: props.certificateFile };
}

export async function prepareMobileAndroid(options = {}) {
  if (process.platform !== 'darwin' && process.platform !== 'linux') throw new Error('Native Android preparation requires macOS or Linux.');
  if (process.version !== 'v26.12.1') throw new Error('Native SDK58 preparation requires Node 26.12.1.');
  const { mode = 'prepare', artifact = 'apk' } = options;
  if (!['prepare', 'build'].includes(mode)) throw new Error('Use --mode prepare or --mode build.');
  if (!['apk', 'aab'].includes(artifact)) throw new Error('Use --artifact apk or --artifact aab.');
  // Play needs 64-bit plus broad device reach; the sideload APK stays arm64-only to bound build time and size.
  const abis = options.abis ?? (artifact === 'aab' ? 'armeabi-v7a,arm64-v8a,x86_64' : 'arm64-v8a');
  if (artifact === 'aab' && !options.uploadKeyProperties) throw new Error('An AAB must be signed with the upload key: pass --upload-key-properties (see scripts/create-android-upload-key.mjs).');
  const uploadKey = options.uploadKeyProperties ? await readUploadKeyProperties(options.uploadKeyProperties) : undefined;
  const toolchain = await resolveAndroidToolchain(options);
  const stage = await createSourceSnapshot({ ...options, prefix: 'blackcrab-android-' }), mobile = path.join(stage.repo, 'apps/mobile');
  const publicConfig = publicBuildConfiguration(options);
  const env = androidBuildEnvironment(stage.root, toolchain, { ...options, publicConfig });
  await Promise.all([fs.mkdir(env.HOME), fs.mkdir(env.TMPDIR), fs.mkdir(env.GRADLE_USER_HOME, { recursive: true }), fs.writeFile(env.NPM_CONFIG_USERCONFIG, '', { mode: 0o600 }), fs.writeFile(env.NPM_CONFIG_GLOBALCONFIG, '', { mode: 0o600 })]);
  const report = { schemaVersion: 1, platform: 'android', mode, artifact, stage: stage.root, repo: stage.repo, sourceManifest: path.join(stage.root, 'artifacts/source-manifest.json'), logs: path.join(stage.root, 'logs'), toolchain, status: 'running', executedOnDevice: false, publicConfiguration: publicConfig };
  const reportPath = path.join(stage.root, 'artifacts/build-report.json');
  const save = () => fs.writeFile(reportPath, JSON.stringify(report, null, 2) + '\n');
  await save();
  const npmCommand = options.npmCli ? process.execPath : 'npm';
  const npmArgs = args => options.npmCli ? [path.resolve(options.npmCli), ...args] : args;
  let step = 0;
  const run = (name, command, args, cwd = stage.repo, timeout) => runLogged(command, args, { cwd, env, timeout, log: path.join(report.logs, `${String(++step).padStart(2, '0')}-${name}.log`) });
  try {
    report.npmCache = await resolveNpmCache(stage.root, options.repoRoot ?? defaultRepo, options.npmCache);
    await run('node-version', process.execPath, ['--version']);
    const npmVersion = (await execute(npmCommand, npmArgs(['--version']), { env })).stdout.trim();
    if (npmVersion !== '12.2.2') throw new Error('Native SDK58 preparation requires npm 12.2.2 (use --npm-cli for an isolated CLI).');
    await run('java-version', path.join(toolchain.javaHome, 'bin/java'), ['-version']);
    report.nativeInstallPolicy = await verifyNativeInstallInputs(stage.repo);
    await run('npm-ci', npmCommand, npmArgs(['ci', '--no-audit', '--no-fund', '--cache', report.npmCache]));
    const load = rel => import(pathToFileURL(path.join(stage.repo, rel)).href);
    const { verifyInstalledGraph } = await load('mobile-experience/installed-graph.mjs');
    try { report.installedGraph = await verifyInstalledGraph({ repoRoot: stage.repo }); }
    catch (error) { if (error.report) report.installedGraph = error.report; throw error; }
    const { applyOwnedMobileBuildPatches, applyExpoModuleScannerBuildPatch } = await load('mobile-experience/build-patches.mjs');
    report.ownedBuildPatches = [await applyOwnedMobileBuildPatches({ repoRoot: stage.repo }), await applyExpoModuleScannerBuildPatch({ repoRoot: stage.repo })];
    const { collectNativeAssetInputs } = await load('mobile-experience/native-assets.mjs');
    const nativeAssets = await collectNativeAssetInputs(stage.repo);
    report.nativeAssetInputs = path.join(stage.root, 'artifacts/native-asset-inputs.json');
    await fs.writeFile(report.nativeAssetInputs, JSON.stringify(nativeAssets, null, 2) + '\n');
    report.dependencies = await verifyNativeDependencyRoots(stage.repo);
    await run('mobile-resources', process.execPath, ['mobile-experience/resources-cli.mjs']);
    const { verifyMobileReactCompiler } = await load('mobile-experience/react-compiler.mjs');
    report.reactCompiler = verifyMobileReactCompiler({ repoRoot: stage.repo });
    report.mobileResources = path.join(mobile, '.generated/RESOURCE-MANIFEST.json');
    report.mobileResourcesSha256 = hash(await fs.readFile(report.mobileResources));

    report.ghosttyHeaders = await stageGhosttyHeaders(path.join(stage.root, 'external/libghostty-vt'));
    const require = createRequire(path.join(mobile, 'package.json'));
    await run('expo-prebuild', process.execPath, [require.resolve('expo/bin/cli'), 'prebuild', '--platform', 'android', '--no-install'], mobile);
    const manifest = await fs.readFile(path.join(mobile, 'android/app/src/main/AndroidManifest.xml'), 'utf8');
    const gradle = await fs.readFile(path.join(mobile, 'android/app/build.gradle'), 'utf8');
    if (!gradle.includes(`applicationId '${EXPECTED_PACKAGE}'`) && !gradle.includes(`applicationId "${EXPECTED_PACKAGE}"`)) throw new Error(`Generated Android project does not use ${EXPECTED_PACKAGE}.`);
    report.androidManifestSha256 = hash(manifest);
    if (mode === 'build') {
      report.entryFile = await resolveNativeEntry(stage.repo);
      // Not exported as ENTRY_FILE: the Android React Native Gradle plugin joins it onto the project directory.
      env.NODE_ENV = 'production'; // only for bundling; npm ci above must keep devDependencies
      const vendorOutputs = path.join(stage.root, 'external/vendor-gradle-outputs');
      report.initScript = path.join(stage.root, 'artifacts/relocate-vendor-build.init.gradle');
      await fs.writeFile(report.initScript, vendorOutputRelocationInitScript(vendorOutputs, { includeDirectory: report.ghosttyHeaders.includeDirectory, signingProperties: uploadKey?.file }));
      report.initScriptSha256 = hash(await fs.readFile(report.initScript));
      const task = artifact === 'aab' ? 'bundleRelease' : 'assembleRelease';
      report.nativeBuild = { task, abis, signing: uploadKey ? `upload key ${uploadKey.keyAlias} (secrets read from a private file at build time)` : 'Expo debug keystore (sideload/internal only)', arguments: gradleReleaseArguments({ abis, initScript: report.initScript, task }) };
      await save();
      await run(`gradle-${task}`, path.join(mobile, 'android/gradlew'), report.nativeBuild.arguments, path.join(mobile, 'android'), 120 * 60_000);
      const outputs = path.join(mobile, 'android/app/build/outputs', artifact === 'aab' ? 'bundle/release' : 'apk/release');
      const found = (await fs.readdir(outputs)).filter(name => name.endsWith(`.${artifact}`));
      if (found.length !== 1) throw new Error(`Expected one release .${artifact}, found ${found.length}.`);
      const built = path.join(outputs, found[0]);
      if (!inside(stage.repo, await fs.realpath(built))) throw new Error('Build output escapes staging.');
      const buildTools = path.join(toolchain.androidHome, 'build-tools');
      const [latest] = (await fs.readdir(buildTools)).sort().reverse();
      const output = report[artifact] = path.join(stage.root, 'artifacts', `blackcrab-remote-release.${artifact}`);
      await fs.copyFile(built, output);
      report[`${artifact}Sha256`] = hash(await fs.readFile(output));
      if (artifact === 'apk') {
        await run('apksigner-verify', path.join(buildTools, latest, 'apksigner'), ['verify', '--verbose', '--print-certs', output]);
        const badging = (await execute(path.join(buildTools, latest, 'aapt2'), ['dump', 'badging', output], { maxBuffer: 16 * 1024 * 1024 })).stdout;
        const pkg = /package: name='([^']+)' versionCode='([^']+)' versionName='([^']+)'/.exec(badging);
        if (!pkg || pkg[1] !== EXPECTED_PACKAGE) throw new Error('APK package identity is not the owned Blackcrab Remote ID.');
        report.apkIdentity = { package: pkg[1], versionCode: pkg[2], versionName: pkg[3], minSdk: /sdkVersion:'(\d+)'/.exec(badging)?.[1], targetSdk: /targetSdkVersion:'(\d+)'/.exec(badging)?.[1] };
      } else {
        const keytool = path.join(toolchain.javaHome, 'bin/keytool');
        await run('jarsigner-verify', path.join(toolchain.javaHome, 'bin/jarsigner'), ['-verify', output]);
        const fingerprint = async args => /SHA256:\s*([0-9A-F:]{95})/.exec((await execute(keytool, args, { maxBuffer: 16 * 1024 * 1024 })).stdout)?.[1];
        const signer = await fingerprint(['-printcert', '-jarfile', output]), expected = await fingerprint(['-printcert', '-file', uploadKey.certificateFile]);
        if (!signer || signer !== expected) throw new Error('AAB is not signed by the upload key.');
        report.signing = { uploadCertificateSha256: signer, keyAlias: uploadKey.keyAlias };
        const manifestBytes = (await execute('unzip', ['-p', output, 'base/manifest/AndroidManifest.xml'], { encoding: 'buffer', maxBuffer: 16 * 1024 * 1024 })).stdout;
        if (!Buffer.from(manifestBytes).includes(Buffer.from(EXPECTED_PACKAGE))) throw new Error('AAB package identity is not the owned Blackcrab Remote ID.');
        report.aabIdentity = { package: EXPECTED_PACKAGE };
      }
      const listing = (await execute('unzip', ['-l', output], { maxBuffer: 64 * 1024 * 1024 })).stdout;
      report.embeddedBundle = /assets\/index\.android\.bundle/.test(listing);
      if (!report.embeddedBundle) throw new Error(`Release ${artifact.toUpperCase()} has no embedded JS bundle.`);
    }
    report.status = mode === 'build' ? 'built' : 'prepared';
    await save();
    return { ...report, reportPath };
  } catch (error) {
    report.status = 'failed';
    await save();
    throw new Error(`Native Android ${mode} failed. Retained isolated inputs and logs at ${stage.root}. ${error.message}`);
  }
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const { values } = parseArgs({ options: {
    mode: { type: 'string', default: 'prepare' }, 'include-working-tree': { type: 'boolean', default: false },
    'npm-cli': { type: 'string' }, 'npm-cache': { type: 'string' }, 'staging-parent': { type: 'string' },
    'java-home': { type: 'string' }, 'android-home': { type: 'string' }, 'gradle-user-home': { type: 'string' }, abis: { type: 'string' }, artifact: { type: 'string', default: 'apk' }, 'upload-key-properties': { type: 'string' },
    'eas-project-id': { type: 'string' }, 'update-channel': { type: 'string' }, 'updates-enabled': { type: 'string' },
  } });
  try {
    console.log(JSON.stringify(await prepareMobileAndroid({
      mode: values.mode, includeWorkingTree: values['include-working-tree'], npmCli: values['npm-cli'], npmCache: values['npm-cache'],
      stagingParent: values['staging-parent'], javaHome: values['java-home'] ?? process.env.JAVA_HOME, androidHome: values['android-home'] ?? process.env.ANDROID_HOME,
      gradleUserHome: values['gradle-user-home'], abis: values.abis, artifact: values.artifact, uploadKeyProperties: values['upload-key-properties'],
      easProjectId: values['eas-project-id'], updateChannel: values['update-channel'], updatesEnabled: values['updates-enabled'],
    }), null, 2));
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
